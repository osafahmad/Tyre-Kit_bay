// Writes src/config/licenseTexts.ts from the licence files shipped with the
// pinned dependencies, so the in-app text is the upstream text, not retyped.
// Run after `npm install` and `pod install` whenever one of these versions
// changes: node scripts/generate-license-texts.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const SOURCES = {
  'apache-2.0': 'ios/Pods/GoogleDataTransport/LICENSE',
  mmkv: 'ios/Pods/MMKVCore/LICENSE.TXT',
  lucide: 'node_modules/lucide-react-native/LICENSE',
};

const clean = text =>
  text
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map(line => line.replace(/[ \t]+$/, ''))
    .join('\n')
    .trim();

const entries = Object.entries(SOURCES)
  .map(([id, file]) => {
    const text = clean(fs.readFileSync(path.join(root, file), 'utf8'));
    return `  // ${file}\n  ${JSON.stringify(id)}: ${JSON.stringify(text)},`;
  })
  .join('\n');

const out = `// GENERATED by scripts/generate-license-texts.js. Don't edit by hand.
// Full licence texts shown in the Third-Party Licenses sheet, copied from the
// licence files shipped with the pinned dependencies.

export const LICENSE_TEXTS = {
${entries}
} as const;

export type LicenseTextId = keyof typeof LICENSE_TEXTS;
`;

fs.writeFileSync(path.join(root, 'src/config/licenseTexts.ts'), out);
